#!/usr/bin/env python3
"""Bundle src/ into files you can paste into a wokwi.com ESP32 project.

wokwi.com builds Arduino sketches, not PlatformIO projects. This script writes
wokwi-web/ with:
  sketch.ino     one line that includes tsp05.h
  tsp05.h        every source file concatenated, with the simulation build flags on top
  diagram.json   copy of ../diagram.json
  libraries.txt  Arduino libraries Wokwi must install

All code lives in tsp05.h on purpose: the Arduino builder auto-generates function
prototypes for .ino files, which breaks code that uses namespaces. Headers are left alone.

Run from anywhere:  python3 firmware/tsp05_main/tools/make_wokwi_web.py
"""
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "wokwi-web"

# Headers first (dependency order), then implementations, then main.
ORDER = [
    "config.h", "stepper_ctrl.h", "tof_swipe.h", "flex_servo.h", "ir_dc.h",
    "stepper_ctrl.cpp", "tof_swipe.cpp", "flex_servo.cpp", "ir_dc.cpp", "main.cpp",
]

# Keep in sync with [env:wokwi] build_flags in platformio.ini.
SIM_FLAGS = {"SIM_TOF": None, "MICROSTEP": "1", "FLEX_STRAIGHT_MV": "0", "FLEX_BENT_MV": "3300"}

LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"[^"]+"\s*$')
PRAGMA_ONCE = re.compile(r"^\s*#\s*pragma\s+once\s*$")


def main() -> None:
    missing = sorted({p.name for p in SRC.iterdir() if p.suffix in (".h", ".cpp")} - set(ORDER))
    if missing:
        raise SystemExit(f"Add these files to ORDER in {__file__}: {missing}")

    parts = [
        "// GENERATED by tools/make_wokwi_web.py from firmware/tsp05_main/src. Do not edit by hand.",
        "#pragma once",
    ]
    for name, value in SIM_FLAGS.items():
        parts.append(f"#define {name}" + (f" {value}" if value else ""))
    for name in ORDER:
        lines = (SRC / name).read_text().splitlines()
        kept = [l for l in lines if not LOCAL_INCLUDE.match(l) and not PRAGMA_ONCE.match(l)]
        parts += ["", f"// ===================== {name} =====================", *kept]

    OUT.mkdir(exist_ok=True)
    (OUT / "tsp05.h").write_text("\n".join(parts) + "\n")
    (OUT / "sketch.ino").write_text(
        "// All code is in tsp05.h (generated by tools/make_wokwi_web.py).\n"
        '#include "tsp05.h"\n'
    )
    (OUT / "libraries.txt").write_text("ESP32Servo\n")
    shutil.copyfile(ROOT / "diagram.json", OUT / "diagram.json")
    print(f"Wrote {OUT}/: sketch.ino, tsp05.h, diagram.json, libraries.txt")


if __name__ == "__main__":
    main()
